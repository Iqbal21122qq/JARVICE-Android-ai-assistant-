package com.example.core.ai

import android.content.Context
import android.net.ConnectivityManager
import android.net.NetworkCapabilities
import com.example.BuildConfig
import com.example.core.model.AiMode
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

data class AiResponse(
    val reasoning: String,
    val shellCommand: String? = null,
    val pythonScript: String? = null,
    val spokenResponse: String,
    val aiMode: AiMode,
    val isAutoGeneratedScript: Boolean = false
)

class HybridIntelligenceEngine(private val context: Context) {

    private val okHttpClient = OkHttpClient.Builder()
        .connectTimeout(15, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .writeTimeout(15, TimeUnit.SECONDS)
        .build()

    // Configurable Local LLM URL (Ollama in Termux or llama.cpp)
    var localLlmUrl: String = "http://127.0.0.1:11434"
    var localLlmModel: String = "llama3.2:1b"

    private fun isNetworkAvailable(): Boolean {
        val cm = context.getSystemService(Context.CONNECTIVITY_SERVICE) as? ConnectivityManager
            ?: return false
        val network = cm.activeNetwork ?: return false
        val capabilities = cm.getNetworkCapabilities(network) ?: return false
        return capabilities.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)
    }

    suspend fun queryJarvis(
        userInput: String,
        systemContextSummary: String
    ): AiResponse = withContext(Dispatchers.IO) {
        val hasNet = isNetworkAvailable()
        val geminiKey = try { BuildConfig.GEMINI_API_KEY } catch (_: Exception) { "" }

        // 1. Try Online Gemini if internet is available and key is configured
        if (hasNet && geminiKey.isNotBlank() && geminiKey != "MY_GEMINI_API_KEY") {
            try {
                val onlineResult = callGeminiApi(userInput, systemContextSummary, geminiKey)
                if (onlineResult != null) {
                    return@withContext onlineResult
                }
            } catch (_: Exception) {
                // Fall through to offline mode
            }
        }

        // 2. Try Offline Local LLM (Termux / Ollama / llama.cpp)
        try {
            val localResult = callLocalLlm(userInput, systemContextSummary)
            if (localResult != null) {
                return@withContext localResult
            }
        } catch (_: Exception) {
            // Local LLM server not reachable, fallback to Autonomous Heuristic Core
        }

        // 3. Fallback: Internal Autonomous Rule & Intent Parser
        executeOfflineHeuristic(userInput, systemContextSummary)
    }

    private fun callGeminiApi(
        prompt: String,
        systemContext: String,
        apiKey: String
    ): AiResponse? {
        val systemInstruction = """
            You are J.A.R.V.I.S., a hyper-intelligent, autonomous AI running on a rooted Android Linux environment.
            Your tone is professional, crisp, and slightly British (like Tony Stark's assistant).
            Current System Context:
            $systemContext

            You have root privileges and can execute shell commands or write Python scripts.
            When you need to perform an action, format your response strictly using these tags:
            [THOUGHT: <brief technical reasoning>]
            [SHELL: <root bash command to execute, or NONE>]
            [PYTHON: <complete python script to write and execute, or NONE>]
            [FINAL_ANSWER: <concise speech text to speak to the user>]
        """.trimIndent()

        val jsonPayload = JSONObject().apply {
            put("contents", JSONArray().apply {
                put(JSONObject().apply {
                    put("parts", JSONArray().apply {
                        put(JSONObject().put("text", "User request: $prompt"))
                    })
                })
            })
            put("systemInstruction", JSONObject().apply {
                put("parts", JSONArray().apply {
                    put(JSONObject().put("text", systemInstruction))
                })
            })
            put("generationConfig", JSONObject().apply {
                put("temperature", 0.4)
                put("maxOutputTokens", 1024)
            })
        }

        val requestUrl = "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key=$apiKey"
        val request = Request.Builder()
            .url(requestUrl)
            .post(jsonPayload.toString().toRequestBody("application/json".toMediaType()))
            .build()

        val response = okHttpClient.newCall(request).execute()
        if (!response.isSuccessful) return null

        val responseBody = response.body?.string() ?: return null
        val json = JSONObject(responseBody)
        val candidates = json.optJSONArray("candidates") ?: return null
        val firstCand = candidates.optJSONObject(0) ?: return null
        val content = firstCand.optJSONObject("content") ?: return null
        val parts = content.optJSONArray("parts") ?: return null
        val rawText = parts.optJSONObject(0)?.optString("text") ?: return null

        return parseAiResponseTags(rawText, AiMode.ONLINE_GEMINI)
    }

    private fun callLocalLlm(
        prompt: String,
        systemContext: String
    ): AiResponse? {
        // Ollama API endpoint: POST /api/generate
        val requestUrl = "$localLlmUrl/api/generate"
        val fullPrompt = """
            System: You are J.A.R.V.I.S., rooted Android assistant.
            System status: $systemContext
            Use format:
            [SHELL: <command or NONE>]
            [FINAL_ANSWER: <spoken text>]
            User: $prompt
            Response:
        """.trimIndent()

        val jsonPayload = JSONObject().apply {
            put("model", localLlmModel)
            put("prompt", fullPrompt)
            put("stream", false)
        }

        val request = Request.Builder()
            .url(requestUrl)
            .post(jsonPayload.toString().toRequestBody("application/json".toMediaType()))
            .build()

        val response = okHttpClient.newCall(request).execute()
        if (!response.isSuccessful) return null

        val body = response.body?.string() ?: return null
        val json = JSONObject(body)
        val rawText = json.optString("response")
        if (rawText.isBlank()) return null

        return parseAiResponseTags(rawText, AiMode.OFFLINE_LOCAL_LLM)
    }

    private fun parseAiResponseTags(rawText: String, mode: AiMode): AiResponse {
        val thoughtRegex = "\\[THOUGHT:(.*?)\\]".toRegex(RegexOption.DOT_MATCHES_ALL)
        val shellRegex = "\\[SHELL:(.*?)\\]".toRegex(RegexOption.DOT_MATCHES_ALL)
        val pythonRegex = "\\[PYTHON:(.*?)\\]".toRegex(RegexOption.DOT_MATCHES_ALL)
        val finalRegex = "\\[FINAL_ANSWER:(.*?)\\]".toRegex(RegexOption.DOT_MATCHES_ALL)

        val thought = thoughtRegex.find(rawText)?.groupValues?.getOrNull(1)?.trim() ?: "Analyzing directive..."
        val shell = shellRegex.find(rawText)?.groupValues?.getOrNull(1)?.trim()
            ?.takeIf { it.isNotBlank() && !it.equals("NONE", ignoreCase = true) }
        val python = pythonRegex.find(rawText)?.groupValues?.getOrNull(1)?.trim()
            ?.takeIf { it.isNotBlank() && !it.equals("NONE", ignoreCase = true) }
        var finalAnswer = finalRegex.find(rawText)?.groupValues?.getOrNull(1)?.trim()

        if (finalAnswer.isNullOrBlank()) {
            finalAnswer = rawText
                .replace(thoughtRegex, "")
                .replace(shellRegex, "")
                .replace(pythonRegex, "")
                .trim()
            if (finalAnswer.isBlank()) {
                finalAnswer = "Executing directive as requested, sir."
            }
        }

        return AiResponse(
            reasoning = thought,
            shellCommand = shell,
            pythonScript = python,
            spokenResponse = finalAnswer,
            aiMode = mode,
            isAutoGeneratedScript = python != null
        )
    }

    private fun executeOfflineHeuristic(
        userInput: String,
        @Suppress("UNUSED_PARAMETER") systemContext: String
    ): AiResponse {
        val lower = userInput.lowercase()

        return when {
            lower.contains("boost") || lower.contains("ram") || lower.contains("clean memory") || lower.contains("cache") -> {
                AiResponse(
                    reasoning = "Initiating memory buffer purge via kernel drop_caches.",
                    shellCommand = "sync && echo 3 > /proc/sys/vm/drop_caches && free -m",
                    spokenResponse = "Flushing kernel memory caches and dropping inactive pages now, sir.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("cpu") || lower.contains("governor") || lower.contains("frequency") -> {
                AiResponse(
                    reasoning = "Querying CPU scaling frequencies and active cluster governor.",
                    shellCommand = "cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_cur_freq 2>/dev/null && cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor 2>/dev/null || cat /proc/cpuinfo | head -n 8",
                    spokenResponse = "Querying CPU frequency scaling and active governor profiles.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("battery") || lower.contains("temperature") || lower.contains("thermal") -> {
                AiResponse(
                    reasoning = "Inspecting thermal sensors and hardware power stats.",
                    shellCommand = "dumpsys battery | grep -E 'level|temperature|health|status'",
                    spokenResponse = "Battery diagnostics retrieved. Thermal sensors are within optimal limits.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("process") || lower.contains("top") || lower.contains("tasks") -> {
                AiResponse(
                    reasoning = "Inspecting active process table for rogue CPU consumers.",
                    shellCommand = "top -n 1 -b -m 8 2>/dev/null || ps -ef | head -n 10",
                    spokenResponse = "Displaying top active Linux processes on your device.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("kill") -> {
                val words = userInput.split(" ")
                val target = words.lastOrNull()?.trim() ?: "unknown"
                AiResponse(
                    reasoning = "Issuing root am force-stop signal to target application.",
                    shellCommand = "am force-stop $target",
                    spokenResponse = "Terminating process tree for $target immediately, sir.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("wifi on") || (lower.contains("wifi") && lower.contains("enable")) -> {
                AiResponse(
                    reasoning = "Invoking svc wifi enable via root shell.",
                    shellCommand = "svc wifi enable",
                    spokenResponse = "Wi-Fi radio interfaces enabled, sir.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("wifi off") || (lower.contains("wifi") && lower.contains("disable")) -> {
                AiResponse(
                    reasoning = "Invoking svc wifi disable via root shell.",
                    shellCommand = "svc wifi disable",
                    spokenResponse = "Wi-Fi radio interfaces disabled.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
            lower.contains("python") || lower.contains("script") -> {
                val sampleScript = """
import sys, os, platform
print(f"J.A.R.V.I.S. Python Worker Online on {platform.system()} {platform.machine()}")
print(f"Active User: {os.getlogin() if hasattr(os, 'getlogin') else 'root'}")
print(f"Kernel Release: {platform.release()}")
                """.trimIndent()
                AiResponse(
                    reasoning = "Writing and staging dynamic diagnostic Python script.",
                    pythonScript = sampleScript,
                    spokenResponse = "Autonomous Python diagnostic script compiled and executed.",
                    aiMode = AiMode.OFFLINE_HEURISTIC,
                    isAutoGeneratedScript = true
                )
            }
            else -> {
                AiResponse(
                    reasoning = "System query received. Running standard environment diagnostic check.",
                    shellCommand = "uname -a && id",
                    spokenResponse = "Standing by, sir. All core subsystems and root privileges are functioning nominally.",
                    aiMode = AiMode.OFFLINE_HEURISTIC
                )
            }
        }
    }

    // Autonomous Self-Healing Diagnostic: Analyzes a failed command and generates a fixed retry
    fun generateSelfHealingFix(
        failedCommand: String,
        errorOutput: String
    ): Pair<String, String>? {
        val err = errorOutput.lowercase()
        return when {
            err.contains("permission denied") -> {
                Pair(
                    "su -c '$failedCommand'",
                    "Detected permission boundary. Elevating execution context directly into root su shell."
                )
            }
            err.contains("read-only file system") -> {
                Pair(
                    "mount -o remount,rw / && $failedCommand",
                    "Target partition is read-only. Remounting root partition with read-write flags."
                )
            }
            err.contains("not found: python3") || err.contains("no such file: python") -> {
                Pair(
                    "export PATH=\$PATH:/data/data/com.termux/files/usr/bin && python3 -c 'print(\"Termux Python linked\")' 2>/dev/null || sh -c '$failedCommand'",
                    "Standard Python binary path missing. Redirecting execution into Termux binary path."
                )
            }
            err.contains("device or resource busy") -> {
                Pair(
                    "sync && sleep 1 && $failedCommand",
                    "Resource lock encountered. Syncing kernel buffers before retrying operation."
                )
            }
            else -> null
        }
    }
}
